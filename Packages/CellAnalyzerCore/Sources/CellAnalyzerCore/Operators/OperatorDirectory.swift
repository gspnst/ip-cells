import Foundation

/// Country and operator lookup for MCC/MNC codes (ITU-T E.212). The operator list is a curated
/// subset of large networks; names change after mergers, so treat them as hints.
public enum OperatorDirectory {
    public struct Country: Sendable, Hashable {
        public let isoCode: String
        public let name: String
        public var flag: String {
            isoCode.uppercased().unicodeScalars.compactMap { UnicodeScalar(127_397 + $0.value) }
                .map(String.init).joined()
        }
    }

    struct PLMNKey: Hashable {
        let mcc: Int, mnc: Int
        init(_ mcc: Int, _ mnc: Int) { self.mcc = mcc; self.mnc = mnc }
    }

    public static func country(mcc: Int) -> Country? {
        if mcc == 1 || mcc == 999 { return Country(isoCode: "XX", name: "Test network") }
        if mcc == 901 { return Country(isoCode: "XX", name: "International / satellite") }
        guard let entry = countries[mcc] else { return nil }
        return Country(isoCode: entry.0, name: entry.1)
    }

    public static func operatorName(mcc: Int, mnc: Int) -> String? {
        operators[PLMNKey(mcc, mnc)]
    }

    /// Human readable "Operator (Country)" or a fallback built from the PLMN.
    public static func describe(mcc: Int?, mnc: Int?) -> String {
        guard let mcc else { return "Unknown network" }
        let country = country(mcc: mcc)
        if let mnc, let name = operatorName(mcc: mcc, mnc: mnc) {
            return country.map { "\(name) (\($0.name))" } ?? name
        }
        if let mnc {
            let plmn = PLMN(mcc: mcc, mnc: mnc)
            return country.map { "\(plmn) (\($0.name))" } ?? plmn.description
        }
        return country?.name ?? "MCC \(mcc)"
    }

    /// Whether a known MCC uses 3-digit MNCs (North America, parts of Latin America & Caribbean, India 405).
    public static func usesThreeDigitMNC(mcc: Int) -> Bool {
        threeDigitMNC.contains(mcc)
    }

    /// True for MCCs that are allocated in E.212 (or reserved for tests).
    public static func isKnownMCC(_ mcc: Int) -> Bool {
        countries[mcc] != nil || mcc == 1 || mcc == 999 || mcc == 901
    }

